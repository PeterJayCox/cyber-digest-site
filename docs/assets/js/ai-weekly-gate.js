/* AI Weekly — draft-release gate.
 *
 * Payload is PBKDF2(SHA-256) -> AES-GCM encrypted at build time, so the draft body is
 * unreadable without the passphrase *even from view-source*. That matters because this
 * page is served from a public GitHub Pages repo: an obfuscated-but-readable gate
 * (base64) would leave draft content exposed in the repository and in raw.githubusercontent.
 *
 * Honest limits: there is no server, so the ciphertext is public and a weak passphrase is
 * brute-forceable offline. This deters casual readers and crawlers; it is not confidentiality
 * against someone who wants in.
 */
(function () {
  var node = document.getElementById('aiw-payload');
  if (!node) { return; }

  var payload;
  try { payload = JSON.parse(node.textContent); } catch (e) { return; }
  if (!payload || !payload.ct) { return; }

  var input = document.getElementById('aiw-pass');
  var form = document.getElementById('aiw-form');
  var err = document.getElementById('aiw-err');
  var out = document.getElementById('aiw-out');
  var lock = document.getElementById('aiw-lock');

  function b64(s) {
    var raw = atob(s), a = new Uint8Array(raw.length);
    for (var i = 0; i < raw.length; i++) { a[i] = raw.charCodeAt(i); }
    return a;
  }
  function say(msg) {
    if (!err) { return; }
    err.textContent = msg;
    err.style.display = 'block';
  }

  function unlock() {
    if (!(window.crypto && window.crypto.subtle)) {
      say('This page needs a secure context (https) to decrypt the draft.');
      return;
    }
    var pw = input ? input.value : '';
    if (!pw) { say('Enter the password.'); return; }
    var enc = new TextEncoder();
    crypto.subtle.importKey('raw', enc.encode(pw), { name: 'PBKDF2' }, false, ['deriveKey'])
      .then(function (base) {
        return crypto.subtle.deriveKey(
          { name: 'PBKDF2', salt: b64(payload.kdf.salt), iterations: payload.kdf.iterations, hash: 'SHA-256' },
          base, { name: 'AES-GCM', length: 256 }, false, ['decrypt']);
      })
      .then(function (key) {
        return crypto.subtle.decrypt({ name: 'AES-GCM', iv: b64(payload.iv) }, key, b64(payload.ct));
      })
      .then(function (plain) {
        /* Decrypted markup is set via innerHTML: <script> inside it will NOT execute and
           the fragment is generated by our own build, never by user input. Because the
           edition fragment carries its own interactive JS (the brief/board view toggle
           and the TOC scrollspy), those script nodes are re-created below so they run.
           Only ever applied to ciphertext we produced ourselves. */
        out.innerHTML = new TextDecoder().decode(plain);
        var scripts = out.querySelectorAll('script');
        for (var i = 0; i < scripts.length; i++) {
          var live = document.createElement('script');
          if (scripts[i].src) { live.src = scripts[i].src; } else { live.textContent = scripts[i].textContent; }
          document.body.appendChild(live);
        }
        out.hidden = false;
        if (lock) { lock.hidden = true; }
        document.title = (payload.title || 'AI Weekly') + ' · draft';
      })
      .catch(function () { say('Incorrect password.'); });
  }

  if (form) { form.addEventListener('submit', function (e) { e.preventDefault(); unlock(); }); }
  if (input) { input.focus(); }
})();
